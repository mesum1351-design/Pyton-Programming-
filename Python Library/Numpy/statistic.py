# Statistics
import numpy as np
# For 1D array
a = np.array([1,2,3,4,5])
# Sum of one Dimension array
print(a.sum())

#Maximum Number
print(a.max())

# Mean
print(a.mean())

# standard daviation
print(a.std())

#variance
print(a.var())

#For nDimension Array
b = np.array([[[1,2,3,4],
             [5,6,7,8],
             [2,4,6,8]]])
# Sum of one Dimension array
print(b.sum())

#Maximum Number
print(b.max())

# Mean
print(b.mean())

# standard daviation
print(b.std())

#variance
print(b.var())
